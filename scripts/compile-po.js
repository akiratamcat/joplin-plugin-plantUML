// Compiles locales/*.po into src/locales.generated.ts so that the plugin can
// look up translations at runtime without bundling a gettext parser.
// Fuzzy and empty entries are skipped (the English source string is used).

const fs = require('fs')
const path = require('path')
const { po } = require('gettext-parser')

const rootDir = path.resolve(__dirname, '..')
const localesDir = path.join(rootDir, 'locales')
const outputFile = path.join(rootDir, 'src', 'locales.generated.ts')

const result = {}
const files = fs.readdirSync(localesDir).filter(f => f.endsWith('.po')).sort()

for (const file of files) {
    const locale = path.basename(file, '.po')
    const parsed = po.parse(fs.readFileSync(path.join(localesDir, file)))
    const catalog = {}
    let total = 0
    let translated = 0
    for (const context of Object.values(parsed.translations)) {
        for (const entry of Object.values(context)) {
            if (!entry.msgid) continue // header
            total++
            const flags = (entry.comments && entry.comments.flag) || ''
            const msgstr = entry.msgstr && entry.msgstr[0]
            if (!msgstr || flags.includes('fuzzy')) continue
            catalog[entry.msgid] = msgstr
            translated++
        }
    }
    result[locale] = catalog
    console.info(`[i18n] ${locale}: ${translated}/${total} strings`)
}

const header = '// AUTO-GENERATED by scripts/compile-po.js from locales/*.po. Do not edit.\n'
const body = `const translations: { [locale: string]: { [msgid: string]: string } } = ${JSON.stringify(result, null, 4)}\n\nexport default translations\n`
fs.writeFileSync(outputFile, header + body, 'utf8')
console.info(`[i18n] Wrote ${path.relative(rootDir, outputFile)} (${files.length} locales)`)
